"""
Real (no-mock) tests for build.py task commands.

Uses actual git dirty state and the --dry-run flag via subprocess.
Requires fhir-omop-ig and matchbox repos cloned alongside matchbox_scripts.
Does not require a running stack, Docker, or network access.

Note: matchbox_scripts itself has pre-existing uncommitted changes
(load_duckdb.py, transforms.py, etl_report_*.html), so dev-overlay will
always be True in tests that call 'run local'. Tests are written to
reflect this real state rather than fighting it.
"""
import subprocess
import sys
import pytest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent.parent))

import build
from build import _detect_dirty, IG_DIR, SCRIPTS_DIR, REPO_ROOT, DQD_DIR

MATCHBOX_DIR = REPO_ROOT / 'matchbox'
BUILD_PY = SCRIPTS_DIR / 'build.py'

# Skip the whole module if the repos aren't cloned.
pytestmark = pytest.mark.skipif(
    not IG_DIR.exists() or not MATCHBOX_DIR.exists(),
    reason='fhir-omop-ig and matchbox repos must be cloned alongside matchbox_scripts',
)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def _run_dry(*args):
    """Call build.py with --dry-run and return parsed output dict."""
    result = subprocess.run(
        [sys.executable, str(BUILD_PY), *args, '--dry-run'],
        capture_output=True, text=True, cwd=str(SCRIPTS_DIR),
    )
    parsed = {}
    for line in result.stdout.splitlines():
        if line.startswith('steps: '):
            parsed['steps'] = line[len('steps: '):].split()
        elif line.startswith('ig-source: '):
            parsed['ig_source'] = line[len('ig-source: '):]
        elif line.startswith('dev-overlay: '):
            parsed['dev_overlay'] = line[len('dev-overlay: '):] == 'True'
    return parsed


def _git_restore(path, cwd):
    subprocess.run(['git', 'restore', str(path)], cwd=str(cwd), check=True)


